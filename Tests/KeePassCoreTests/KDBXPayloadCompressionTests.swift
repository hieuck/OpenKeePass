import Foundation
import XCTest
@testable import KeePassCore

final class KDBXPayloadCompressionTests: XCTestCase {
    func testNoneReturnsPayloadUnchanged() throws {
        let payload = Data("plain xml".utf8)

        XCTAssertEqual(try KDBXPayloadCompression.decode(payload, compression: KDBXHeader.Compression.none), payload)
    }

    func testGzipInflatesPayload() throws {
        let compressed = Data([
            0x1F, 0x8B, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x02, 0xFF, 0xB3, 0xF1, 0x4E, 0x4D, 0x0D, 0x48,
            0x2C, 0x2E, 0x76, 0xCB, 0xCC, 0x49, 0xB5, 0xB3,
            0x09, 0xCA, 0xCF, 0x2F, 0xB1, 0xB3, 0x71, 0x2F,
            0xCA, 0x2F, 0x2D, 0xB0, 0xB3, 0xF1, 0x4B, 0xCC,
            0x4D, 0xB5, 0x03, 0x89, 0xD8, 0xE8, 0x83, 0x99,
            0x36, 0xFA, 0x50, 0x09, 0x7D, 0x88, 0x32, 0x7D,
            0x64, 0xAD, 0x00, 0xF7, 0x2B, 0xA0, 0x2F, 0x48,
            0x00, 0x00, 0x00
        ])

        let payload = try KDBXPayloadCompression.decode(compressed, compression: .gzip)

        XCTAssertEqual(
            String(data: payload, encoding: .utf8),
            "<KeePassFile><Root><Group><Name>Root</Name></Group></Root></KeePassFile>"
        )
    }
}
